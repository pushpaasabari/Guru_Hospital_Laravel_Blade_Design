/**
 * Flat list of all tests for quick lookup and datalist suggestions.
 */
export const ALL_LAB_TESTS: LabCatalogItem[] = LAB_CATALOG.flatMap((cat) => cat.tests);

/**
 * Find catalog test by name or ID (case-insensitive fuzzy match).
 */
export const findLabTest = (name: string): LabCatalogItem | undefined => {
  if (!name || !name.trim()) return undefined;
  const clean = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!clean) return undefined;

  return ALL_LAB_TESTS.find((t) => {
    const idClean = t.id.toLowerCase().replace(/[^a-z0-9]/g, '');
    const nameClean = t.name.toLowerCase().replace(/[^a-z0-9]/g, '');
    return idClean === clean || nameClean === clean || nameClean.startsWith(clean) || clean.startsWith(idClean);
  });
};

